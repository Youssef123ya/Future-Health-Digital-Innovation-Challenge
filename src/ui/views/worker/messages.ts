/** Worker-app catalogs by language (English is the source; every other language is a draft translation). */
export const WORKER_MESSAGES: Readonly<Record<LangCode, WorkerCatalog>> = Object.freeze({
  en: EN,
  ar: AR,
  ur: UR,
  hi: HI,
  ne: NE,
  bn: BN,
  ml: ML,
  tl: TL,
})

/** Every worker-app message key, in source order (tests check that each language provides each one). */
export const WORKER_MESSAGE_KEYS: readonly WorkerMessageKey[] = Object.freeze(Object.keys(EN) as WorkerMessageKey[])

/**
 * `wt(lang, key, params?)`: a worker-app string with `{param}` and plural interpolation (shared i18n formatMessage, so
 * numbers are locale-formatted and string params are bidi-isolated in Arabic and Urdu). Falls back to English, then to
 * the key, so a worker never sees a blank. [ENG, fail-safe; same chain as i18n `translate`]
 */
export function wt(lang: LangCode, key: WorkerMessageKey, params?: MessageParams): string {
  const code: LangCode = isLangCode(lang) ? lang : 'en'
  const own = WORKER_MESSAGES[code][key]
  if (typeof own === 'string' && own.trim() !== '') return formatMessage(own, code, params)
  const source = EN[key]
  return typeof source === 'string' ? formatMessage(source, 'en', params) : String(key)
}
